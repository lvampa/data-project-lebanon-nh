import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";
import betterTailwindcss from "eslint-plugin-better-tailwindcss";

const noArbitraryValues = [
  "warn",
  {
    restrict: [
      {
        pattern: String.raw`\[([^\[\]]*?)\](?!:)`,
        message: "Use a token from frontend/shared/styles instead of an arbitrary value.",
      },
    ],
  },
];

// Classes are checked against the stylesheet of the app that renders them.
// Shared components are checked against web's, which imports the same shared styles as admin.
function tailwindFor(files, entryPoint) {
  return {
    ...betterTailwindcss.configs["correctness-error"],
    files,
    settings: { "better-tailwindcss": { entryPoint, detectComponentClasses: true } },
    rules: {
      ...betterTailwindcss.configs["correctness-error"].rules,
      "better-tailwindcss/no-restricted-classes": noArbitraryValues,
    },
  };
}

export default defineConfig([
  ...nextVitals,
  ...nextTs,
  { settings: { next: { rootDir: ["web/", "admin/"] } } },
  tailwindFor(["web/**/*.{ts,tsx}", "shared/**/*.{ts,tsx}"], "web/app/globals.css"),
  tailwindFor(["admin/**/*.{ts,tsx}"], "admin/app/globals.css"),
  {
    // Generated by the shadcn CLI. Hand edits are lost on the next `shadcn add`.
    files: ["shared/components/ui/**"],
    rules: { "better-tailwindcss/no-restricted-classes": "off" },
  },
  globalIgnores([
    "**/.next/**",
    "**/out/**",
    "**/build/**",
    "**/next-env.d.ts",
    // Playwright outputs.
    "**/test-results/**",
    "**/playwright-report/**",
    "**/blob-report/**",
    "**/playwright/.cache/**",
  ]),
]);
